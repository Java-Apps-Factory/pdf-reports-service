-- Seed reference data for Virginia (SPEC section 7). Repeatable and idempotent: re-running only
-- inserts missing rows and refreshes names; it never touches ACTIVE flags or RPT_STATE.ACTIVE_RUN_ID.
-- Standard MERGE syntax that runs unchanged on H2 (MODE=DB2) and IBM DB2 LUW.

MERGE INTO RPT_STATE t
USING (VALUES ('VA', 'Virginia')) AS s (STATE_CODE, STATE_NAME)
ON t.STATE_CODE = s.STATE_CODE
WHEN MATCHED THEN UPDATE SET STATE_NAME = s.STATE_NAME
WHEN NOT MATCHED THEN INSERT (STATE_CODE, STATE_NAME, ACTIVE) VALUES (s.STATE_CODE, s.STATE_NAME, 1);

