/**
 * Two application contexts ("nodes") against one H2 file database (SPEC section 20, Phase 3 acceptance): they
 * never claim the same document, and a run started on one node is generated by both.
 */
class TwoNodeClaimIT {

    private static final int DOCUMENTS = 300;
    private static final int BATCH = 5;

    @Test
    void racingClaimsNeverOverlap() throws Exception {
        String url = databaseUrl("race");
        try (ConfigurableApplicationContext nodeA = start(url, "node-a", false, 1031);
                ConfigurableApplicationContext nodeB = start(url, "node-b", false, 1032)) {
            JdbcTemplate jdbc = nodeA.getBean(JdbcTemplate.class);
            TrackingRows rows = new TrackingRows(jdbc);
            Instant now = nodeA.getBean(DbClock.class).now();
            long runId = rows.insertRun("RUNNING", now);
            for (int i = 0; i < DOCUMENTS; i++) {
                rows.insertDocument(runId, String.format("%05d", i), "PENDING", 0, null, null, now.plusMillis(i));
            }

            CountDownLatch go = new CountDownLatch(1);
            ExecutorService threads = Executors.newFixedThreadPool(2);
            try {
                Future<List<Long>> a = threads.submit(claimAll(nodeA, "node-a", go, jdbc, runId));
                Future<List<Long>> b = threads.submit(claimAll(nodeB, "node-b", go, jdbc, runId));
                go.countDown();
                List<Long> claimedByA = a.get();
                List<Long> claimedByB = b.get();

                Set<Long> union = new HashSet<>(claimedByA);
                union.addAll(claimedByB);
                assertThat(claimedByA).doesNotHaveDuplicates().doesNotContainAnyElementsOf(claimedByB);
                assertThat(claimedByB).doesNotHaveDuplicates();
                assertThat(union).hasSize(DOCUMENTS);
                assertThat(claimedByA).isNotEmpty();
                assertThat(claimedByB).isNotEmpty();
                for (Map<String, Object> row : jdbc.queryForList("SELECT DOC_ID, STATUS, GENERATION_ATTEMPTS, "
                        + "LEASE_OWNER FROM REPORT_DOCUMENT WHERE RUN_ID = ?", runId)) {
                    long docId = ((Number) row.get("DOC_ID")).longValue();
                    assertThat(row.get("STATUS")).asString().isEqualTo("GENERATING");
                    assertThat(((Number) row.get("GENERATION_ATTEMPTS")).intValue()).isEqualTo(1);
                    assertThat(row.get("LEASE_OWNER")).isEqualTo(claimedByA.contains(docId) ? "node-a" : "node-b");
                }
            } finally {
                threads.shutdownNow();
            }
        }
    }

    @Test
    void aRunStartedOnOneNodeIsGeneratedByBothExactlyOnce() {
        String url = databaseUrl("flow");
        try (ConfigurableApplicationContext nodeA = start(url, "node-a", true, 1033);
                ConfigurableApplicationContext nodeB = start(url, "node-b", true, 1034)) {
            ReportRun run = nodeA.getBean(ReportRunService.class).startRun(StartRunCommand.builder().stateCode("VA")
                    .triggerType(TriggerType.API).requestedBy("two-node-test").build());
            TrackingRows rows = new TrackingRows(nodeB.getBean(JdbcTemplate.class));

            rows.awaitRunStatus(run.getRunId(), "DISPATCHING", "COMPLETED");

            List<Map<String, Object>> documents = rows.documentsOf(run.getRunId());
            assertThat(documents).hasSize(run.getTotalDocuments()).allSatisfy(d -> {
                assertThat(((String) d.get("STATUS")).trim()).isIn("GENERATED", "SENDING", "SENT");
                assertThat(((Number) d.get("GENERATION_ATTEMPTS")).intValue()).isEqualTo(1);
            });
            long claimedA = nodeA.getBean(GenerationPoller.class).claimedTotal();
            long claimedB = nodeB.getBean(GenerationPoller.class).claimedTotal();
            assertThat(claimedA + claimedB).isEqualTo(run.getTotalDocuments());
            Integer content = nodeA.getBean(JdbcTemplate.class).queryForObject(
                    "SELECT COUNT(*) FROM REPORT_CONTENT c JOIN REPORT_DOCUMENT d ON d.DOC_ID = c.DOC_ID "
                            + "WHERE d.RUN_ID = ?", Integer.class, run.getRunId());
            assertThat(content).isEqualTo(run.getTotalDocuments());
        }
    }

    private static Callable<List<Long>> claimAll(ConfigurableApplicationContext node, String owner,
            CountDownLatch go, JdbcTemplate jdbc, long runId) {
        DocumentClaimRepository claims = node.getBean(DocumentClaimRepository.class);
        DbClock clock = node.getBean(DbClock.class);
        return () -> {
            go.await();
            List<Long> claimed = new ArrayList<>();
            while (pending(jdbc, runId) > 0) {
                Instant now = clock.now();
                for (Claim claim : claims.claimForGeneration(BATCH, owner, now, now.plus(Duration.ofMinutes(15)))) {
                    claimed.add(claim.docId());
                }
            }
            return claimed;
        };
    }

    private static int pending(JdbcTemplate jdbc, long runId) {
        return jdbc.queryForObject("SELECT COUNT(*) FROM REPORT_DOCUMENT WHERE RUN_ID = ? AND STATUS = 'PENDING'",
                Integer.class, runId);
    }

    private static String databaseUrl(String name) {
        Path dir = Paths.get("target", "two-node");
        try {
            Files.createDirectories(dir);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        return "jdbc:h2:file:" + dir.toAbsolutePath().resolve(name + "-" + UUID.randomUUID())
                + ";MODE=DB2;DATABASE_TO_UPPER=TRUE";
    }

    private static ConfigurableApplicationContext start(String url, String nodeId, boolean jobs, int brokerId) {
        return new SpringApplicationBuilder(ReportServiceApplication.class)
                .web(WebApplicationType.NONE)
                .profiles("h2", "test")
                .run("--spring.datasource.url=" + url,
                        "--reporting.node-id=" + nodeId,
                        "--reporting.jobs.enabled=" + jobs,
                        "--reporting.generation.temp-dir=target/fips-reports-" + nodeId,
                        "--spring.artemis.embedded.server-id=" + brokerId);
    }
}
